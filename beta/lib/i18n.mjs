export const dictionaries = { ru, kk, en };
export const localeFor = (lang) =>
  ({ ru: "ru-RU", kk: "kk-KZ", en: "en-GB" })[lang] || "ru-RU";
export function translator(lang = "ru") {
  const dictionary = dictionaries[lang] || ru;
  return (key, args = {}) =>
    (dictionary[key] || ru[key] || key).replace(/\{(\w+)\}/g, (_, k) =>
      String(args[k] ?? ""),
    );
}
